import { start } from "./lib.mjs";
const { page, api, clickAt, shot, sleep, finish, problems } = await start();
const A = "/api/m/assembly";
// ---- Assembly Studio: a gear pair and a pin that the wheel's teeth hit
let r = await api("POST", `${A}/assemblies`, { name: "Motion demo" });
if (r.status !== 200) throw new Error(JSON.stringify(r));
const aid = r.body.assembly?.id ?? r.body.id;
const ins = async (code, params) => { const x = await api("POST", `${A}/assemblies/${aid}/instances`, { toolbox: { code, params } }); if (x.status !== 200) throw new Error(JSON.stringify(x.body)); return x.body.result.instance; };
const pin = await ins("spur_gear", { M: 2, Z: 18, B: 10, BORE: 8 });
const wheel = await ins("spur_gear", { M: 2, Z: 36, B: 10, BORE: 10 });
const peg = await ins("dowel", { D: 3, L: 20 });
const a = 54, pb = 10, ph = (180 - 0.5 * pb) % pb, c = Math.cos(ph * Math.PI / 180), s = Math.sin(ph * Math.PI / 180);
await api("PATCH", `${A}/assemblies/${aid}/instances/${wheel}`, { T: [c, -s, 0, a, s, c, 0, 0, 0, 0, 1, 0], fixed: false });
await api("PATCH", `${A}/assemblies/${aid}/instances/${peg}`, { T: [1, 0, 0, a, 0, 1, 0, 36, 0, 0, 1, -5] });
const pp = (await api("GET", `${A}/assemblies/${aid}`)).body;
const j = async b => { const x = await api("POST", `${A}/assemblies/${aid}/joints`, b); if (x.status !== 200) throw new Error(JSON.stringify(x.body)); return x.body; };
const j1 = (await j({ type: "revolute", name: "Pinion", insts: [pin], p: [0, 0, 0], dir: [0, 0, 1] })).result;
const j2 = (await j({ type: "revolute", name: "Wheel", insts: [wheel], p: [a, 0, 0], dir: [0, 0, 1] })).result;
const v = await j({ type: "gear", a: j1.id, b: j2.id });
console.log("joints", JSON.stringify(v.joints.map(x => [x.id, x.type, x.ratio ?? null, x.teeth ?? null])));
await page.goto(`${process.env.FW_URL}/app/modules/assembly?assembly=${aid}`, { waitUntil: "domcontentloaded" });
await page.waitForSelector("[data-testid=asm-viewport]", { timeout: 30000 });
await sleep(2500);
await clickAt("button[role=tab][id$=\"-trigger-motion\"]");
await sleep(800);
await shot("motion_01_joints");
const t0 = Date.now();
await clickAt("[data-run-motion]");
await page.waitForSelector("[data-motion-summary]", { timeout: 600000 });
console.log("assembly sweep", (Date.now() - t0) / 1000, "s:", await page.$eval("[data-motion-summary]", e => e.textContent));
await sleep(1500);
await shot("motion_02_worst_step");
await page.$eval("[data-motion-scrub]", el => { const set = Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, "value").set; set.call(el, "3"); el.dispatchEvent(new Event("input", { bubbles: true })); });
await sleep(1000);
await shot("motion_03_scrubbed");
// ---- Design Office: gear reducer, placeholder assembly, Check motion
r = await api("POST", "/api/office/programs", { name: "Gearbox MX-1", brief: "A single-stage spur gear reducer (gearbox), ratio 3:1, for a small conveyor drive.", planner: "standard" });
if (r.status !== 200) throw new Error(JSON.stringify(r));
const pid = r.body.id ?? r.body.program?.id;
r = await api("POST", `/api/office/programs/${pid}/gates/brief/approve`, {});
console.log("brief", r.status);
r = await api("POST", `/api/office/programs/${pid}/gates/icd/approve`, {});
console.log("icd", r.status, r.status !== 200 ? JSON.stringify(r.body) : "");
for (let k = 0; k < 120; k++) { const x = await api("GET", `/api/office/programs/${pid}/assembly`); if (x.body?.status && x.body.status !== "building") { console.log("program assembly", x.body.status, x.body.summary); break; } await sleep(2000); }
await page.goto(`${process.env.FW_URL}/app/office/programs/${pid}`, { waitUntil: "domcontentloaded" });
await sleep(2500);
await clickAt("button[role=tab][id$=\"-trigger-assembly\"]");
await page.waitForSelector("[data-check-motion]", { timeout: 60000 });
await sleep(3000);
const t1 = Date.now();
await clickAt("[data-check-motion]");
await page.waitForSelector("[data-program-motion] [data-motion-summary]", { timeout: 900000 });
console.log("program sweep", (Date.now() - t1) / 1000, "s:", await page.$eval("[data-program-motion] [data-motion-summary]", e => e.textContent));
await sleep(1500);
await shot("motion_04_program");
console.log("problems", problems.length);
await finish();
